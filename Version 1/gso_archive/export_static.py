"""Export the archive as static JSON files + the dashboard, for GitHub Pages.

Layout written to OUT_DIR:
    index.html, css/, js/, vendor/       (copied from web/)
    config.js                            (mode: "static")
    data/meta.json, data/status.json
    data/daily/<series>.json             (full-history daily stats)
    data/points/<series>/<YYYY-MM>.json  (raw points per MYT month)
    data/exports/<series>/<YYYY-MM>.csv  (monthly CSV downloads)
"""

from __future__ import annotations

import json
import shutil
from datetime import date, datetime, timedelta
from pathlib import Path

from sqlalchemy import func, select
from sqlalchemy.engine import Engine

from . import analytics, db, export
from .config import Settings
from .timeutil import MYT, UTC, ensure_utc

MARKER = ".gso-static-export"


def _month_bounds(year: int, month: int) -> tuple[datetime, datetime]:
    start = datetime(year, month, 1, tzinfo=MYT)
    nxt = datetime(year + (month == 12), month % 12 + 1, 1, tzinfo=MYT)
    return start.astimezone(UTC), nxt.astimezone(UTC)


def _write(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, separators=(",", ":")), encoding="utf-8")


def export_site(engine: Engine, settings: Settings, out_dir: Path, months: int | None = None) -> dict:
    out_dir = Path(out_dir)
    if out_dir.exists():
        # Only ever delete a directory this command created.
        if any(out_dir.iterdir()) and not (out_dir / MARKER).exists():
            raise FileExistsError(f"{out_dir} exists and is not a previous static export; refusing to delete it")
        shutil.rmtree(out_dir)
    shutil.copytree(settings.web_dir, out_dir)
    (out_dir / MARKER).write_text("generated by gso-archive export-static\n")
    (out_dir / "config.js").write_text(
        'window.GSO_CONFIG = {"mode": "static", "apiBase": "", "dataBase": "data"};\n', encoding="utf-8"
    )
    data = out_dir / "data"
    files = 0
    with engine.connect() as conn:
        meta = analytics.meta(conn)
        meta["static_export"] = True
        _write(data / "meta.json", meta)
        _write(data / "status.json", analytics.status(conn, settings.adapters, settings.gso_live_enabled))
        files += 2
        o = db.observations.c
        for s in meta["series"]:
            info = analytics.get_series(conn, s["key"])
            if info is None or info.kind == "forecast" and not s["count"]:
                continue
            if info.kind == "forecast":
                lo = conn.execute(select(func.min(db.forecasts.c.target_time)).where(db.forecasts.c.series_id == info.id)).scalar()
                hi = conn.execute(select(func.max(db.forecasts.c.target_time)).where(db.forecasts.c.series_id == info.id)).scalar()
            else:
                lo = conn.execute(select(func.min(o.obs_time)).where(o.series_id == info.id)).scalar()
                hi = conn.execute(select(func.max(o.obs_time)).where(o.series_id == info.id)).scalar()
            if lo is None:
                continue
            first = ensure_utc(lo).astimezone(MYT).date()
            last = ensure_utc(hi).astimezone(MYT).date()
            if months:
                first = max(first, (last.replace(day=1) - timedelta(days=31 * (months - 1))).replace(day=1))
            if info.kind != "forecast":
                _write(data / "daily" / f"{info.key}.json",
                       {"series": info.key, "unit": info.unit, "rows": analytics.daily(conn, info, first, last),
                        "is_demo": info.is_demo})
                files += 1
            y, m = first.year, first.month
            while (y, m) <= (last.year, last.month):
                t0, t1 = _month_bounds(y, m)
                payload = analytics.points(conn, info, t0, t1, max_points=10**9)
                tag = f"{y}-{m:02d}"
                _write(data / "points" / info.key / f"{tag}.json", payload)
                if info.kind != "forecast":
                    csv_path = data / "exports" / info.key / f"{tag}.csv"
                    csv_path.parent.mkdir(parents=True, exist_ok=True)
                    csv_path.write_text(export.to_csv(export.rows_for_export([(payload, info)])), encoding="utf-8")
                    files += 1
                files += 1
                y, m = (y + 1, 1) if m == 12 else (y, m + 1)
    return {"out_dir": str(out_dir), "files": files, "generated_for": date.today().isoformat()}
