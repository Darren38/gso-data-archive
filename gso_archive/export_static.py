"""Export the archive as static JSON files + the dashboard, for GitHub Pages.

Layout written to OUT_DIR:
    index.html, css/, js/, vendor/       (copied from web/)
    config.js                            (mode: "static")
    data/meta.json, data/status.json
    data/daily/<series>.json             (full-history daily stats)
    data/points/<series>/<YYYY-MM>.json  (raw points per MYT month)
    data/exports/<series>/<YYYY-MM>.csv  (monthly CSV downloads)
    data/archive.sqlite3.gz              (the whole archive, SQLite; also how the next
                                          GitHub Actions run carries the archive over)
"""

from __future__ import annotations

import json
import shutil
from datetime import date, datetime, timedelta
from pathlib import Path

from sqlalchemy import func, select
from sqlalchemy.engine import Engine

from . import analytics, db, export
from .config import Settings
from .sealing import passphrase
from .timeutil import MYT, UTC, ensure_utc, to_utc_iso

RECENT_DAYS = 3  # data/points/<key>/recent.json: the newest days of every series in one small file

MARKER = ".gso-static-export"


def _month_bounds(year: int, month: int) -> tuple[datetime, datetime]:
    start = datetime(year, month, 1, tzinfo=MYT)
    nxt = datetime(year + (month == 12), month % 12 + 1, 1, tzinfo=MYT)
    return start.astimezone(UTC), nxt.astimezone(UTC)


def _write(path: Path, obj) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, separators=(",", ":")), encoding="utf-8")


def export_site(engine: Engine, settings: Settings, out_dir: Path, months: int | None = None,
                include_archive: bool = True) -> dict:
    out_dir = Path(out_dir)
    if out_dir.exists():
        # Only ever delete a directory this command created.
        if any(out_dir.iterdir()) and not (out_dir / MARKER).exists():
            raise FileExistsError(f"{out_dir} exists and is not a previous static export; refusing to delete it")
        shutil.rmtree(out_dir)
    shutil.copytree(settings.web_dir, out_dir)
    (out_dir / MARKER).write_text("generated by gso-archive export-static\n")
    (out_dir / "config.js").write_text(
        'window.GSO_CONFIG = {"mode": "static", "apiBase": "", "dataBase": "data"};\n', encoding="utf-8"
    )
    data = out_dir / "data"
    files = 0
    with engine.connect() as conn:
        meta = analytics.meta(conn)
        meta["static_export"] = True
        meta["collection"] = collection_info(settings, conn)
        # A locked archive (ARCHIVE_PASSPHRASE set) is for the owner only, so the About page offers no download.
        meta["archive_download"] = bool(include_archive and engine.dialect.name == "sqlite" and not passphrase())
        _write(data / "meta.json", meta)
        _write(data / "status.json", analytics.status(conn, settings.adapters, settings.gso_live_enabled))
        files += 2
        for key in analytics.TABLES:
            _write(data / "tables" / f"{key}.json", analytics.table(conn, key))
            files += 1
        o = db.observations.c
        for s in meta["series"]:
            info = analytics.get_series(conn, s["key"])
            if info is None or info.kind == "forecast" and not s["count"]:
                continue
            if info.kind == "forecast":
                lo = conn.execute(select(func.min(db.forecasts.c.target_time)).where(db.forecasts.c.series_id == info.id)).scalar()
                hi = conn.execute(select(func.max(db.forecasts.c.target_time)).where(db.forecasts.c.series_id == info.id)).scalar()
            else:
                lo = conn.execute(select(func.min(o.obs_time)).where(o.series_id == info.id)).scalar()
                hi = conn.execute(select(func.max(o.obs_time)).where(o.series_id == info.id)).scalar()
            if lo is None:
                continue
            first = ensure_utc(lo).astimezone(MYT).date()
            last = ensure_utc(hi).astimezone(MYT).date()
            if months:
                first = max(first, (last.replace(day=1) - timedelta(days=31 * (months - 1))).replace(day=1))
            if info.kind != "forecast":
                _write(data / "daily" / f"{info.key}.json",
                       {"series": info.key, "unit": info.unit, "rows": analytics.daily(conn, info, first, last),
                        "is_demo": info.is_demo})
                files += 1
            y, m = first.year, first.month
            while (y, m) <= (last.year, last.month):
                t0, t1 = _month_bounds(y, m)
                payload = analytics.points(conn, info, t0, t1, max_points=10**9)
                tag = f"{y}-{m:02d}"
                _write(data / "points" / info.key / f"{tag}.json", payload)
                if info.kind != "forecast":
                    csv_path = data / "exports" / info.key / f"{tag}.csv"
                    csv_path.parent.mkdir(parents=True, exist_ok=True)
                    csv_path.write_text(export.to_csv(export.rows_for_export([(payload, info)])), encoding="utf-8")
                    files += 1
                files += 1
                y, m = (y + 1, 1) if m == 12 else (y, m + 1)
            # The last RECENT_DAYS days in one small file: the Overview and "today" views need only these, not
            # whole months (late in a month the Overview fetched about 3 MB; data.js uses this file when it can).
            t_hi = ensure_utc(hi) + timedelta(seconds=1)
            _write(data / "points" / info.key / "recent.json",
                   {**analytics.points(conn, info, t_hi - timedelta(days=RECENT_DAYS), t_hi + timedelta(days=3), max_points=10**9),
                    "recent_from": to_utc_iso(t_hi - timedelta(days=RECENT_DAYS))})
            files += 1
        # LSS solar farms, one file per day: every farm's output at every collected moment (Solar page, "a moment"
        # and capacity factor views).
        days = analytics.farm_days(conn)
        if months:
            days = days[: 31 * months]
        _write(data / "farms" / "index.json", {"days": days})
        for d in days:
            _write(data / "farms" / f"{d}.json", analytics.farms_day(conn, date.fromisoformat(d)))
        files += 1 + len(days)
    archive_bytes = None
    if include_archive and engine.dialect.name == "sqlite":
        from .archive_sync import ARCHIVE_FILE, write_snapshot
        from .sealing import SUFFIX, seal

        if passphrase():  # locked: only the encrypted copy is published
            import tempfile

            with tempfile.TemporaryDirectory() as tmp:
                write_snapshot(settings.database_url, Path(tmp) / ARCHIVE_FILE)
                seal(Path(tmp) / ARCHIVE_FILE, data / (ARCHIVE_FILE + SUFFIX))
            archive_bytes = (data / (ARCHIVE_FILE + SUFFIX)).stat().st_size
        else:
            archive_bytes = write_snapshot(settings.database_url, data / ARCHIVE_FILE)
        files += 1
    return {"out_dir": str(out_dir), "files": files, "archive_bytes": archive_bytes,
            "generated_for": date.today().isoformat()}


def collection_info(settings: Settings, conn=None) -> dict:
    """What the site's "Auto" labels say about how often data is collected.

    `observed_interval_seconds` is measured from the run log (median gap between recent scheduled
    collections), so the label reports what actually happens, not just what was asked for.
    """
    info = {"mode": settings.collection_mode, "interval_seconds": settings.collect_interval_seconds,
            "live_enabled": settings.gso_live_enabled, "observed_interval_seconds": None}
    if conn is not None:
        info["observed_interval_seconds"] = analytics.observed_interval(conn)
    return info
